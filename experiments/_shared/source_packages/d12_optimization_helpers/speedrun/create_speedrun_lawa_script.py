#!/usr/bin/env python3
"""Create a NanoChat speedrun script that saves late model-only LAWA snapshots.

Run install_speedrun_lawa_hook.py first. This script copies runs/speedrun.sh,
changes the pretraining module to scripts.base_train_lawa, and appends the
lightweight snapshot arguments to the base-training command. It leaves the
upstream speedrun script untouched.
"""
from __future__ import annotations

import argparse
from pathlib import Path


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", type=Path, required=True)
    ap.add_argument("--source", default="runs/speedrun.sh")
    ap.add_argument("--dest", default="runs/speedrun_lawa.sh")
    ap.add_argument("--snapshot-every", type=int, default=32)
    ap.add_argument("--snapshot-start-frac", type=float, default=0.82)
    ap.add_argument("--snapshot-keep", type=int, default=40)
    ap.add_argument("--snapshot-dtype", choices=["float32", "bfloat16", "float16"], default="bfloat16")
    ap.add_argument("--snapshot-dir", required=True)
    args = ap.parse_args()

    src = args.repo / args.source
    dst = args.repo / args.dest
    text = src.read_text()
    if "scripts.base_train" not in text:
        raise SystemExit(f"no scripts.base_train command in {src}")
    text = text.replace("scripts.base_train", "scripts.base_train_lawa", 1)

    flags = (
        f"--lawa-snapshot-every={args.snapshot_every} "
        f"--lawa-snapshot-start-frac={args.snapshot_start_frac} "
        f"--lawa-snapshot-keep={args.snapshot_keep} "
        f"--lawa-snapshot-dtype={args.snapshot_dtype} "
        f"--lawa-snapshot-dir={args.snapshot_dir}"
    )
    marker = "--run=$WANDB_RUN"
    if marker not in text:
        raise SystemExit(f"could not find {marker!r} in {src}")
    text = text.replace(marker, flags + " " + marker, 1)
    header = (
        "# AUTO-GENERATED by optimization_paper_suite_v1.\n"
        "# Upstream source is left unchanged. Lightweight snapshot I/O is outside\n"
        "# the measured optimizer-step timer, but report true end-to-end overhead too.\n"
    )
    dst.write_text(header + text)
    dst.chmod(0o755)
    print(f"wrote {dst}")
    print("snapshot dir:", args.snapshot_dir)


if __name__ == "__main__":
    main()
